function packageExport({ subpath, suffix, names, typeNames, types, source, bundle }) {
  const manifest = Object.freeze({
    types,
    ...(source ? { import: source } : {}),
    default: bundle,
  });
  return Object.freeze({
    subpath,
    specifier: `${PACKAGE_METADATA.name}${suffix}`,
    names: Object.freeze(names),
    typeNames: Object.freeze(typeNames),
    manifest,
  });
}
